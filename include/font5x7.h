// Character lookup: returns index in font5x7 array
static inline uint8_t get_font_index(char c) {
    if (c == ' ') return 0;
    if (c >= '0' && c <= '9') return 1 + (c - '0');
    if (c == ':') return 11;
    if (c == '-') return 12;
    if (c == '_') return 13;
    if (c >= 'a' && c <= 'z') return 14 + (c - 'a');
    if (c >= 'A' && c <= 'Z') return 14 + (c - 'A'); // Map uppercase to lowercase
    return 0; // Default to space for unknown characters
}

